import { useQuery } from '@tanstack/react-query'
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card'
import { AiBadge, EmptyState, ErrorState, LoadingRows } from '@/components/common'
import { ApiError, api } from '@/lib/api'
import { containsArabicScript, formatDuration } from '@/lib/status'
import type { StructuredSummary } from '@/lib/types'

const SECTIONS: { key: keyof StructuredSummary; label: string }[] = [
  { key: 'parent_guardian_statements', label: 'Parent or guardian statements' },
  { key: 'student_statements', label: 'Student statements' },
  { key: 'educational_background', label: 'Educational background' },
  { key: 'interests_and_activities', label: 'Interests and activities' },
  { key: 'school_expectations', label: 'School-related expectations' },
  { key: 'interviewer_documented_observations', label: 'Observations stated aloud by the interviewer' },
  { key: 'important_topics', label: 'Important topics discussed' },
  { key: 'follow_up_questions', label: 'Questions requiring follow-up' },
  { key: 'unclear_or_missing_information', label: 'Unclear or missing information' },
]

function Item({ text }: { text: string }) {
  const rtl = containsArabicScript(text)
  return (
    <li dir={rtl ? 'rtl' : 'auto'} lang={rtl ? 'ur' : undefined} className={rtl ? 'urdu' : undefined}>
      {text}
    </li>
  )
}

export function SummaryPanel({ interviewId }: { interviewId: string }) {
  const summary = useQuery({ queryKey: ['summary', interviewId], queryFn: () => api.summary(interviewId), retry: (n, e) => !(e instanceof ApiError && e.status === 404) && n < 2 })
  if (summary.isPending) return <LoadingRows rows={6} />
  if (summary.isError)
    return summary.error instanceof ApiError && summary.error.status === 404 ? (
      <EmptyState title="Summary not ready" description="The structured summary is generated after the transcript." />
    ) : (
      <ErrorState error={summary.error} onRetry={() => summary.refetch()} />
    )
  const { data, provider, model_name, prompt_version } = summary.data
  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex flex-wrap items-center gap-2 text-base">
          Structured summary <AiBadge />
        </CardTitle>
        <CardDescription>
          Generated by {provider} · {model_name} · prompt {prompt_version}. It may omit or misstate what was said. It is not an assessment of the child and contains no admission
          recommendation.
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-6">
        <section>
          <h3 className="mb-1 text-sm font-semibold">Interview overview</h3>
          <p className="text-sm text-muted-foreground">{data.interview_overview || 'Not mentioned'}</p>
        </section>
        <div className="grid gap-6 md:grid-cols-2">
          {SECTIONS.map(({ key, label }) => {
            const items = (data[key] as string[] | undefined) ?? []
            return (
              <section key={key}>
                <h3 className="mb-1 text-sm font-semibold">{label}</h3>
                {items.length ? (
                  <ul className="list-disc space-y-1 pl-5 text-sm">
                    {items.map((t, i) => (
                      <Item key={i} text={t} />
                    ))}
                  </ul>
                ) : (
                  <p className="text-sm text-muted-foreground italic">Not mentioned</p>
                )}
              </section>
            )
          })}
        </div>
        {data.evidence?.length > 0 && (
          <section>
            <h3 className="mb-2 text-sm font-semibold">Transcript evidence cited by the model</h3>
            <ul className="space-y-2 text-sm">
              {data.evidence.map((e, i) => (
                <li key={i} className="rounded-md border-l-2 border-primary/40 bg-muted/40 px-3 py-2">
                  {e.start_seconds !== null && <span className="mr-2 font-mono text-xs text-muted-foreground">{formatDuration(e.start_seconds)}</span>}
                  <span dir="auto">“{e.quote}”</span>
                </li>
              ))}
            </ul>
          </section>
        )}
      </CardContent>
    </Card>
  )
}
